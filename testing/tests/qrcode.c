// fuji_qrcode_output() drains the device's cached matrix, so each case needs its own encode.
static bool qr_encode_ready(uint8_t version, qr_ecc_t ecc, qr_output_mode_t mode,
                             uint8_t *data, uint16_t data_len, unsigned long *out_len)
{
#ifdef FN_BROKEN_fuji_qrcode_input
  return false;
#else
  if (!fuji_qrcode_input(data, data_len))
    return false;

  if (!fuji_qrcode_encode(version, ecc, false))
    return false;

  *out_len = 0;
  return fuji_qrcode_length(mode, out_len);
#endif
}

// Bundled to fit CoCo's code budget; unrolled per-step calls didn't fit.
static bool qr_check_mode(uint8_t version, qr_ecc_t ecc, qr_output_mode_t mode,
                           uint8_t *data, uint16_t data_len,
                           const uint8_t *expected, uint16_t expected_len)
{
#ifdef FN_BROKEN_fuji_qrcode_output
  return false;
#else
  unsigned long enc_len;

  if (!qr_encode_ready(version, ecc, mode, data, data_len, &enc_len))
    return false;

  if (enc_len != expected_len)
    return false;

  memset(g.qrcode_verify.output1, 0, sizeof(g.qrcode_verify.output1));
  if (!fuji_qrcode_output(g.qrcode_verify.output1, expected_len))
    return false;

  return memcmp(g.qrcode_verify.output1, expected, expected_len) == 0;
#endif
}

// ANSI/SVG renderings run into the kilobytes, so only success/length is checked here.
static bool qr_encode_and_drain(uint8_t version, qr_ecc_t ecc, bool shorten,
                                 qr_output_mode_t mode, uint8_t *data, uint16_t data_len,
                                 unsigned long *total_len)
{
#ifdef FN_BROKEN_fuji_qrcode_input
  return false;
#else
  unsigned long remaining;
  uint16_t chunk;

  if (!fuji_qrcode_input(data, data_len))
    return false;

  if (!fuji_qrcode_encode(version, ecc, shorten))
    return false;

  *total_len = 0;
  if (!fuji_qrcode_length(mode, total_len) || !*total_len)
    return false;

  remaining = *total_len;
  for (; remaining; remaining -= chunk) {
    chunk = remaining > sizeof(g.net) ? sizeof(g.net) : (uint16_t) remaining;
    if (!fuji_qrcode_output(g.net, chunk))
      return false;
  }

  return true;
#endif
}

void test_fuji_qrcode(void)
{
  uint8_t input[] = QR_INPUT;
  uint8_t url_input[] = QR_INPUT_URL;
  uint16_t in_len;
  uint16_t url_len;
  unsigned long enc_len;
  bool ok;
  int ret;

  in_len = (uint16_t)strlen((char *)input);
  url_len = (uint16_t)strlen((char *)url_input);

  SECTION("qrcode low-level interface (fuji_qrcode_input/encode/length/output)");

#ifdef FN_BROKEN_fuji_qrcode_input
  SKIP(fuji_qrcode_input);
#else
  ok = fuji_qrcode_input(input, in_len);
  TEST("fuji_qrcode_input succeeds", ok);
#endif

#ifdef FN_BROKEN_fuji_qrcode_encode
  SKIP(fuji_qrcode_encode);
#else
  ok = fuji_qrcode_encode(0, QR_ECC_LOW, false);
  TEST("fuji_qrcode_encode succeeds", ok);
#endif

#ifdef FN_BROKEN_fuji_qrcode_length
  SKIP(fuji_qrcode_length);
#else
  enc_len = 0;
  ok = fuji_qrcode_length(QR_OUTPUT_MODE_BINARY, &enc_len);
  TEST("fuji_qrcode_length succeeds", ok);
  TEST("Encoded length matches expected reference", enc_len == sizeof(QR_BINARY_OUT));
#endif

#ifdef FN_BROKEN_fuji_qrcode_output
  SKIP(fuji_qrcode_output);
#else
  memset(g.qrcode_verify.output1, 0, sizeof(g.qrcode_verify.output1));
  ok = fuji_qrcode_output(g.qrcode_verify.output1, (uint16_t) enc_len);
  TEST("fuji_qrcode_output succeeds", ok);
  printf("  QR code encoded: %lu bytes (low-level, binary)\n", enc_len);
  TEST("Binary output matches expected reference bytes",
       memcmp(g.qrcode_verify.output1, QR_BINARY_OUT, sizeof(QR_BINARY_OUT)) == 0);

  SECTION("qrcode_create (high-level helper)");
#endif

#ifdef FN_BROKEN_qrcode_create
  SKIP(qrcode_create);
#else
  memset(g.qrcode_verify.output2, 0, sizeof(g.qrcode_verify.output2));
  ret = qrcode_create(0, QR_ECC_LOW, false, QR_OUTPUT_MODE_BINARY,
                       input, in_len, g.qrcode_verify.output2, sizeof(g.qrcode_verify.output2));
  TEST("qrcode_create succeeds", ret > 0);
  printf("  QR code encoded: %d bytes (qrcode_create, binary)\n", ret);
  TEST("qrcode_create length matches low-level length", (unsigned long) ret == enc_len);
  TEST("qrcode_create output matches low-level output",
       memcmp(g.qrcode_verify.output1, g.qrcode_verify.output2, (size_t) ret) == 0);
#endif

  SECTION("qrcode output modes and ECC levels (exact match)");

  TEST("Bitmap output matches expected reference",
       qr_check_mode(0, QR_ECC_LOW, QR_OUTPUT_MODE_BITMAP, input, in_len,
                     QR_BITMAP_OUT, sizeof(QR_BITMAP_OUT)));
  TEST("ATASCII output matches expected reference",
       qr_check_mode(0, QR_ECC_LOW, QR_OUTPUT_MODE_ATASCII, input, in_len,
                     QR_ATASCII_OUT, sizeof(QR_ATASCII_OUT)));
  TEST("PETSCII output matches expected reference",
       qr_check_mode(0, QR_ECC_LOW, QR_OUTPUT_MODE_PETSCII, input, in_len,
                     QR_PETSCII_OUT, sizeof(QR_PETSCII_OUT)));

  // Regression check for the qrcode_minVersion() auto+non-LOW-ECC bug; matches the LOW baseline.
  TEST("Auto version with non-LOW ECC succeeds",
       qr_check_mode(0, QR_ECC_HIGH, QR_OUTPUT_MODE_BINARY, input, in_len,
                     QR_BINARY_OUT, sizeof(QR_BINARY_OUT)));

  // Explicit versions: auto (0) would settle on LOW for this input regardless of requested ECC.
  TEST("ECC MEDIUM output matches expected reference",
       qr_check_mode(2, QR_ECC_MEDIUM, QR_OUTPUT_MODE_BINARY, input, in_len,
                     QR_BINARY_MEDIUM_OUT, sizeof(QR_BINARY_MEDIUM_OUT)));
  TEST("ECC QUARTILE output matches expected reference",
       qr_check_mode(2, QR_ECC_QUARTILE, QR_OUTPUT_MODE_BINARY, input, in_len,
                     QR_BINARY_QUART_OUT, sizeof(QR_BINARY_QUART_OUT)));
  TEST("ECC HIGH output matches expected reference",
       qr_check_mode(3, QR_ECC_HIGH, QR_OUTPUT_MODE_BINARY, input, in_len,
                     QR_BINARY_HIGH_OUT, sizeof(QR_BINARY_HIGH_OUT)));
  TEST("Explicit version output matches expected reference",
       qr_check_mode(QR_EXPLICIT_VERSION, QR_ECC_LOW, QR_OUTPUT_MODE_BINARY, input, in_len,
                     QR_BINARY_V2_OUT, sizeof(QR_BINARY_V2_OUT)));

  SECTION("qrcode ANSI/SVG/shorten (protocol only)");

  enc_len = 0;
  ok = qr_encode_and_drain(0, QR_ECC_LOW, false, QR_OUTPUT_MODE_ANSI, input, in_len, &enc_len);
  TEST("ANSI output round-trip succeeds", ok);

  enc_len = 0;
  ok = qr_encode_and_drain(0, QR_ECC_LOW, false, QR_OUTPUT_MODE_SVG, input, in_len, &enc_len);
  TEST("SVG output round-trip succeeds", ok);

  enc_len = 0;
  ok = qr_encode_and_drain(0, QR_ECC_LOW, true, QR_OUTPUT_MODE_BINARY, url_input, url_len, &enc_len);
  TEST("Shorten round-trip succeeds", ok);

  END_OF_TEST();
}
